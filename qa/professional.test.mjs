import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{},structuredClone};
for(const source of ['vendor/papaparse.min.js','src/utils.js','src/custom-values.js','src/professional.js','data/atlas-data.js'])vm.runInNewContext(await readFile(new URL('../'+source,import.meta.url),'utf8'),context);
const {AtlasProfessional:pro,MOUSE_ATLAS_DATA:data}=context.window;
const Papa=context.Papa;
const region=data.regions.find(region=>region.id==='CA1');
const state={values:{CA1:1,'CA1|L':3},familyValues:{HPF:2},structureValues:{},statistics:{},autoRange:true,hemisphere:'B'};
assert.equal(pro.resolve(region,'L',state).value,3);
assert.equal(pro.resolve(region,'R',state).value,1);
assert.equal(pro.resolve(region,'B',state).value,1);
delete state.values.CA1;
assert.equal(pro.resolve(region,'R',state).value,2);
const parsed=pro.parseCSV('region,hemisphere,value\nCA1,L,3\nCA1,R,-2\nMOp,B,0\nCA1,wrong,5','region',data,Papa);
assert.equal(parsed.patch['CA1|L'],3);assert.equal(parsed.patch['CA1|R'],-2);assert.equal(parsed.patch.MOp,0);assert.equal(parsed.invalid.length,1);
assert.equal(pro.parseCSV('region,value\nCA1,3','region',data,Papa).patch.CA1,3);
assert.equal(pro.parseCSV('脑区,半球,数值\nCA1,左,3','region',data,Papa).patch['CA1|L'],3);
assert.equal(data.coordinates.nativeOrientation,'PIR');
const hpf=data.ontology.find(node=>node.acronym==='HPF');
state.structureValues[hpf.id]=4;delete state.values['CA1|L'];
assert.equal(pro.resolve(region,'L',state).value,4);
state.structureValues[pro.key(hpf.id,'L')]=5;
assert.equal(pro.resolve(region,'L',state).value,5);
assert.equal(pro.resolve(region,'R',state).value,4);
state.values.CA1=0;assert.equal(pro.resolve(region,'L',state).value,0);
assert.equal(pro.parseCSV('structure_id,value\n'+region.structureId+',7','region',data,Papa).patch.CA1,7);
const statistics=pro.parseCSV('region,hemisphere,value,p,q,n\nCA1,L,3,0.01,0.04,8\nCA1,R,-2,0.1,0.2,8\nDG,B,0,0,0,10\nMOp,B,1,2,0.1,5','region',data,Papa);
assert.equal(statistics.invalid.length,1);
assert.equal(statistics.statistics['region:DG'].p,0);
const statisticalState={...state,values:statistics.patch,familyValues:{},structureValues:{},statistics:statistics.statistics,symmetricRange:true,statFilter:'q',statThreshold:.05};
assert.equal(pro.passes(pro.resolve(region,'L',statisticalState),statisticalState),true);
assert.equal(pro.passes(pro.resolve(region,'R',statisticalState),statisticalState),false);
assert.equal(pro.passes({value:1,statistics:{}},statisticalState),false);
assert.deepEqual(Array.from(pro.range(data,statisticalState)),[-3,3]);
statisticalState.statFilter='value';statisticalState.absoluteThreshold=3;
assert.equal(pro.passes({value:-3,statistics:{}},statisticalState),true);
assert.equal(pro.passes({value:2.9,statistics:{}},statisticalState),false);
for(const orientation of ['coronal','sagittal','horizontal']){
  const point={ap:6.8,ml:-1.695,dv:4},position=orientation==='coronal'?point.ap:orientation==='sagittal'?point.ml:point.dv;
  const pixel=pro.pointToPlane(orientation,point),restored=pro.pointFromPlane(orientation,...pixel,position);
  for(const axis of ['ap','ml','dv'])assert(Math.abs(point[axis]-restored[axis])<1e-9,orientation+':'+axis);
}
assert.equal(pro.pointFromPlane('coronal',.5,.5,0).ml,-5.695);
assert.equal(pro.pointFromPlane('sagittal',1319.5,.5,0).ap,0);
const project=pro.project(data,statisticalState,[{file:'simulated.csv',text:'region,value\nCA1,3'}]);
assert.equal(pro.readProject(JSON.parse(JSON.stringify(project)),data).history[0].file,'simulated.csv');
assert.throws(()=>pro.readProject({...project,atlas:{...project.atlas,fingerprint:'different'}},data),/图谱版本/);
assert.throws(()=>pro.readProject({...project,version:99},data),/版本/);
console.log(JSON.stringify({hemisphere:'passed',hierarchy:'passed',statistics:'passed',coordinates:'passed',project:'passed',csv:'passed',ontology:data.ontology.length}));
